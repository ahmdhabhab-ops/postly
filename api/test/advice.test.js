test('Excel export: valid workbook, plan + steps sheets, formulas neutralised, owner only', async () => {
  const buf = await buildPlanWorkbook({
    campaign: { title: '=HYPERLINK("http://evil")', platform: 'Instagram', status: 'pending', budget_per_day: 20, duration_days: 7 },
    brief: { objective: '+cmd', audience: { age_min: 24, age_max: 38, genders: 'All', locations: ['Lebanon'], interests: ['Weddings'], notes: '' }, placements: ['Reels'],
      creative: { formats: ['Reel'], ideas: ['@idea'] }, copy: { headline: 'H', primary_text: 'T', cta: 'Learn more' }, landing: 'https://x.example', kpis: ['CPL'], assumptions: [], questions: [] },
    business: { name: 'Einvite', website: 'einvite.me' }, notes: ['No pixel'],
  });
  assert.equal(buf.subarray(0, 2).toString(), 'PK');           // xlsx is a zip
  const wb = new ExcelJS.Workbook(); await wb.xlsx.load(buf);
  assert.deepEqual(wb.worksheets.map((w) => w.name), ['Campaign plan', 'Steps to launch']);
  const rows = []; wb.getWorksheet('Campaign plan').eachRow((r) => rows.push([r.getCell(1).value, r.getCell(2).value]));
  assert.ok(rows.some(([k, v]) => k === 'Budget' && v === '$20 per day'));
  assert.ok(rows.some(([k, v]) => k === 'Total budget' && v === '$140'));
  for (const [, v] of rows) assert.ok(typeof v !== 'string' || !/^[=+\-@]/.test(v), `formula-like cell: ${v}`);
  assert.ok(wb.getWorksheet('Steps to launch').rowCount >= 6);
  assert.ok(launchSteps('Google')[0].includes('Google Ads'));

  const owner = await signup('xl1@z.com');
  script = [tool('Instagram'), txt('{}'), txt('Done')];
  const chat = await owner.post('/api/chat', { message: 'Create an Instagram campaign for me.' });
  const id = chat.json.campaign.id;
  const dl = await owner.get(`/api/campaigns/${id}/plan.xlsx`);
  assert.equal(dl.status, 200);
  assert.match(dl.headers.get('content-type'), /spreadsheetml/);
  assert.match(dl.headers.get('content-disposition'), /attachment; filename="[\w-]+-plan\.xlsx"/);
  assert.equal(dl.buf.subarray(0, 2).toString(), 'PK');
  assert.equal((await (await signup('xl2@z.com')).get(`/api/campaigns/${id}/plan.xlsx`)).status, 404);
  assert.equal((await client().get(`/api/campaigns/${id}/plan.xlsx`)).status, 401);
});
