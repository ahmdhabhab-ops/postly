function client() {
  let cookie = '';
  const call = async (method, path, body) => {
    const res = await fetch(url + path, { method, headers: { 'content-type': 'application/json', ...(cookie && { cookie }) }, body: body === undefined ? undefined : JSON.stringify(body) });
    for (const c of res.headers.getSetCookie?.() ?? []) cookie = c.split(';')[0];
    const buf = Buffer.from(await res.arrayBuffer()); const text = buf.toString('utf8'); let json; try { json = JSON.parse(text); } catch {}
    return { status: res.status, json, text, buf, headers: res.headers };
  };
  return { get: (p) => call('GET', p), post: (p, b = {}) => call('POST', p, b), put: (p, b) => call('PUT', p, b) };
}
const signup = async (email) => { const c = client(); await c.post('/api/auth/register', { email, password: 'correct horse 1', businessName: 'Einvite' }); return c; };
const tool = (platform) => ({ stop_reason: 'tool_use', content: [{ type: 'tool_use', id: 'tu_1', name: 'create_campaign_draft', input: { platform } }] });
const txt = (t) => ({ stop_reason: 'end_turn', content: [{ type: 'text', text: t }] });

const ADVICE = [
  { platform: 'Instagram', fit: 'Best fit', why: 'Couples browse wedding ideas visually.', budget_share: 60, first_step: 'Reel of an invite being made' },
  { platform: 'Google', fit: 'Good fit', why: 'Searches for digital wedding invitations in Lebanon.', budget_share: 40, first_step: 'Keywords' },
  { platform: 'TikTok', fit: 'Later', why: 'Needs lots of video.', budget_share: 30, first_step: '' },
  { platform: 'Myspace', fit: 'Best fit', why: 'not a real option', budget_share: 100 },
  { platform: 'Facebook', fit: 'whatever', why: 'x'.repeat(999), budget_share: 500 },
];

test('advice is limited to known platforms, ranked, clamped; "Later" gets no budget', () => {
  const a = sanitizeAdvice(ADVICE);
  assert.deepEqual(a.map((x) => x.platform), ['Instagram', 'Google', 'Facebook', 'TikTok']);   // Myspace dropped, best first
  assert.equal(a.find((x) => x.platform === 'Facebook').budget_share, 100);
  assert.equal(a.find((x) => x.platform === 'Facebook').why.length, 260);
  assert.equal(a.find((x) => x.platform === 'TikTok').budget_share, 0);
  assert.deepEqual(sanitizeAdvice('nope'), []);
  assert.equal(sanitizeAdvice(fallbackAdvice({})).length, 5);
});

test('channel advice: generated by the model, stored, readable later, per user', async () => {
  const c = await signup('adv1@z.com');
  await c.put('/api/business', { description: 'Digital wedding invitations', country: 'Lebanon', budget: '$100 – $300' });
  assert.deepEqual((await c.get('/api/advice/channels')).json.advice, null);
  calls = []; script = [txt('Here: ' + JSON.stringify(ADVICE))];
  const r = await c.post('/api/advice/channels');
  assert.equal(r.status, 200);
  assert.equal(r.json.ai, true);
  assert.equal(r.json.advice[0].platform, 'Instagram');
  assert.match(calls[0].system, /ONLY these platforms/);
  assert.match(calls[0].messages[0].content, /Digital wedding invitations/);
  const saved = (await c.get('/api/advice/channels')).json;
  assert.equal(saved.advice.length, 4);
  assert.deepEqual((await (await signup('adv2@z.com')).get('/api/advice/channels')).json.advice, null);
  assert.equal((await client().post('/api/advice/channels')).status, 401);
  const me = (await c.get('/api/me')).json.business;
  assert.ok(!('channel_advice' in me));
});

